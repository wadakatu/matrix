// npm run build: tokens (Terrazzo), the flattened stylesheet and the fonts, into dist/.
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

process.chdir(join(import.meta.dirname, ".."));
rmSync("dist", { recursive: true, force: true });

// 1. Tokens: dist/tokens.css, tokens.json, tokens.d.ts.
execFileSync("node_modules/.bin/tz", ["build", "--quiet"], { stdio: "inherit" });

// 2. Elements, the head script and the strings: tsc, ESM and declarations (01, "Build").
execFileSync("node_modules/.bin/tsc", ["-p", "tsconfig.json"], { stdio: "inherit" });

// 3. One flattened stylesheet, in layer order. Components and effects join this list as they arrive.
export const COMPONENTS = ["root", "logo", "mark", "nav", "control", "header", "menu", "lang", "footer", "panel", "lede", "figures", "inline-list", "log", "meta", "moved", "switch", "name", "stream", "streams", "readings", "terminal", "guide", "prompt", "run", "fetch", "login", "swatch", "takeover", "chips", "modeline"];
export const EFFECTS = ["rain", "scanlines", "boot", "curtain", "rewards"];
const STYLESHEETS = ["src/css/index.css", "dist/tokens.css", "src/css/reset.css", "src/css/base.css", ...COMPONENTS.map((c) => `src/components/${c}/${c}.css`), ...EFFECTS.map((e) => `src/effects/${e}/${e}.css`), "src/css/utilities.css"];
writeFileSync("dist/matrix.css", STYLESHEETS.map((f) => readFileSync(f, "utf8")).join("\n"));

// 4. Fonts: Fontsource's @font-face rules for the weights in use, WOFF2 only, files copied
// into the package so that no page requests another origin (D9).
const FONTS = [
  ["@fontsource/ibm-plex-mono", [400, 500, 700]],
  ["@fontsource/m-plus-1-code", [400, 500]],
  ["@fontsource/dotgothic16", [400]],
];
const require = createRequire(import.meta.url);
mkdirSync("dist/fonts");
let fontsCss = "/* Generated by `npm run build` from the Fontsource packages. OFL-1.1: copyright and licence in fonts/*.LICENSE.txt. Do not edit. */\n";
for (const [pkg, weights] of FONTS) {
  const dir = dirname(require.resolve(`${pkg}/package.json`));
  // OFL-1.1 §2: the copyright notice and licence travel with every copy of the font files.
  copyFileSync(join(dir, "LICENSE"), join("dist/fonts", `${pkg.split("/")[1]}.LICENSE.txt`));
  for (const w of weights) {
    const css = readFileSync(join(dir, `${w}.css`), "utf8").replace(
      /src: url\(\.\/files\/([^)]+\.woff2)\) format\('woff2'\)(, url\([^)]+\) format\('woff'\))?/g,
      (_, file) => {
        copyFileSync(join(dir, "files", file), join("dist/fonts", file));
        return `src: url(./fonts/${file}) format('woff2')`;
      },
    );
    if (/\.woff\)/.test(css)) throw new Error(`${pkg} ${w}: an @font-face kept a non-WOFF2 source`);
    fontsCss += css;
  }
}
writeFileSync("dist/fonts.css", fontsCss);

console.log("✔ build: dist/tokens.{css,json,d.ts}, dist/{elements,head,strings}, dist/matrix.css, dist/fonts.css");
